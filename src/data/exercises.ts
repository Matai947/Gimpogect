// Generic words like «кардио» or «гиря» made technique cards pop up out of context.
for (const e of exercises) e.aliases = e.aliases.filter((a) => !['кардио', 'гиря', 'интервалы', 'растяжка', 'ходьба', 'дорожка', 'мост'].includes(a));

export function findExercise(query: string): Exercise | undefined {
  const q = query.toLowerCase();
  return exercises.find((e) => e.name.toLowerCase() === q) ?? exercises.find((e) => q.includes(e.name.toLowerCase()) || e.aliases.some((a) => q.includes(a)));
}

export function exerciseById(id: string) {
  return exercises.find((e) => e.id === id);
}
