-- Seven Gym database on our own Postgres: the same tables as on Supabase.
--   sudo -u postgres psql -c "create database sevengym"
--   sudo -u postgres psql -d sevengym -f deploy/schema.sql
-- Then set the password of the `authenticator` role (the one PostgREST signs in with):
--   sudo -u postgres psql -d sevengym -c "alter role authenticator password 'A-LONG-RANDOM-PASSWORD'"

create table if not exists clients (id text primary key, data jsonb not null, updated_at timestamptz not null default now());
create table if not exists sales (id text primary key, ts bigint not null, data jsonb not null);
create table if not exists visits (id bigint generated by default as identity primary key, ts bigint not null, club text not null, member text not null, kind text not null);
create table if not exists leads (id text primary key, ts bigint not null, data jsonb not null);
create table if not exists trainer_sessions (id text primary key, ts bigint not null, data jsonb not null);
create table if not exists settings (key text primary key, data jsonb not null);
create table if not exists clicks (id bigint generated by default as identity primary key, ts bigint not null, kind text not null, target text not null, src text not null);

-- the reports read by time
create index if not exists sales_ts on sales (ts);
create index if not exists visits_ts on visits (ts);
create index if not exists trainer_sessions_ts on trainer_sessions (ts);

-- PostgREST listens on 127.0.0.1 only. Without a token it is `web_anon`, which may do nothing;
-- our server sends a token signed with PostgREST's jwt-secret for the role `web_app`, which has the rights.
do $$ begin
  if not exists (select from pg_roles where rolname = 'web_anon') then create role web_anon nologin; end if;
  if not exists (select from pg_roles where rolname = 'web_app') then create role web_app nologin; end if;
  if not exists (select from pg_roles where rolname = 'authenticator') then create role authenticator noinherit login; end if;
end $$;
grant web_anon to authenticator;
grant web_app to authenticator;
grant usage on schema public to web_app;
grant select, insert, update, delete on all tables in schema public to web_app;
grant usage, select on all sequences in schema public to web_app;
